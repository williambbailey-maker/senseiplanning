// Generates supabase/seed.sql from supabase/seed-items.json.
import { readFileSync, writeFileSync } from 'node:fs';

const items = JSON.parse(readFileSync(new URL('../supabase/seed-items.json', import.meta.url), 'utf8'));
const TRACKS = ['Product', 'Legal', 'Infra & SEO', 'Comms', 'Day 30', 'Day 60', 'Day 90'];
const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const perTrack = {};
const rows = items.map((it) => {
  if (!TRACKS.includes(it.track)) throw new Error(`Unknown track ${it.track}`);
  const order = (perTrack[it.track] = (perTrack[it.track] ?? -1) + 1);
  return `  (${q(it.track)}, ${q(it.title)}, ${q(it.owner)}, ${it.due ? `date ${q(it.due)}` : 'null'}, ${q(it.status)}, '${String(it.notes ?? '').replace(/'/g, "''")}', ${order})`;
});

const sql = `-- Seed: the Sensei launch project. Generated by scripts/gen-seed.mjs from seed-items.json.
-- Safe to re-run: does nothing if a project named 'Sensei launch' already exists.

with p as (
  insert into plan.projects (name, target_date, tracks)
  select 'Sensei launch', date '2026-11-01',
         array['${TRACKS.join("','")}']::text[]
  where not exists (select 1 from plan.projects where name = 'Sensei launch')
  returning id
)
insert into plan.items (project_id, track, title, owner, due, status, notes, sort_order)
select p.id, v.track, v.title, v.owner, v.due, v.status, v.notes, v.sort_order
from p, (values
${rows.join(',\n')}
) as v(track, title, owner, due, status, notes, sort_order);
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql: ${items.length} items`);
